# Generates MBSEQ_HW.V4 for the 4-OLED front panel (left PCB + 4 column PCBs) from the midiphy hwcfg: every BUTTON_/LED_/
# ENC_ entry is first cleared ("0 0"), then assigned from the PCB input/output mapping (README.md, build_left.py,
# build_column.py). Copy the result to the SD card as MBSEQ_HW.V4 when the new hardware is in use.
import os, re
D = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(D, "..", "..", "apps", "sequencers", "midibox_seq_v4", "hwcfg", "midiphy_lh", "MBSEQ_HW.V4")
OUT = os.path.join(D, "MBSEQ_HW.V4")

# ---- DIN (MIOS32: SR 1 = first register after the core; DIN pin n = 74HC165 input Dn) ----
btn = {}
left_sr1 = ["STEP_VIEW", "TRACK_SEL", "PAR_LAYER_SEL", "TRG_LAYER_SEL", "INS_SEL", "MUTE", "PHRASE", "BOOKMARK"]
left_sr2 = ["SOLO", "METRONOME", "LOOP", "RECORD", "LIVE", "REW", "FWD", "STOP"]
for p, n in enumerate(left_sr1): btn[n] = (1, p)
for p, n in enumerate(left_sr2): btn[n] = (2, p)
btn["ENC_DATAWHEEL"] = (3, 2); btn["PLAY"] = (3, 3); btn["PAUSE"] = (3, 4)          # SR3 D0/D1 = datawheel A/B
fn = ["COPY", "PASTE", "CLEAR", "MOVE", "SCROLL", "FAST", "ALL", "SELECT", "DOWN", "UP", "EXIT", "MENU", "EDIT", "PATTERN", "SONG", "UTILITY"]
enc = {"DATAWHEEL": (1 + 2, 0)}
for col in range(4):                                     # column k: SR 4+3k (GP, select), 5+3k (function, encoder push), 6+3k (encoder A/B)
    s1, s2, s3 = 4 + 3 * col, 5 + 3 * col, 6 + 3 * col
    for i in range(4):
        n = 4 * col + i + 1
        btn["GP%d" % n] = (s1, i)
        btn["DIRECT_TRACK%d" % n] = (s1, 4 + i)
        btn[fn[4 * col + i]] = (s2, i)
        btn["ENC%d" % n] = (s2, 4 + i)
        enc["GP%d" % n] = (s3, 2 * i)
# ---- DOUT: SR 1/2 = the two 74HC595 of the left PCB (DOUT pin 0 = QH ... pin 7 = QA, MIOS32 shifts MSB first) ----
led = {}
for q, n in enumerate(["STEP_VIEW", "TRACK_SEL", "PAR_LAYER_SEL", "TRG_LAYER_SEL", "INS_SEL", "MUTE", "PHRASE", "BOOKMARK"]):
    led[n] = (1, 7 - q)                                  # QA..QH
for q, n in enumerate(["SOLO", "METRONOME", "LOOP", "RECORD", "LIVE", "BEAT"]):
    led[n] = (2, 7 - q)
# virtual DOUT registers (not fitted): read back by seq_rgbled.c and shown on the SK6812 chain
for i, n in enumerate(fn):
    led[n] = (7 + i // 8, i % 8)
for i, n in enumerate(["REW", "FWD", "STOP", "PLAY", "PAUSE"]):
    led[n] = (9, i)
gp = {"GP_DOUT_L_SR": 3, "GP_DOUT_R_SR": 4, "GP_DOUT_L2_SR": 5, "GP_DOUT_R2_SR": 6}

out, seen = [], set()
for line in open(SRC, newline="").read().replace("\r\n", "\n").split("\n"):
    m = re.match(r"^(BUTTON|LED|ENC)_(\S+)(\s+)(\S+)(\s+)(\S+)(.*)$", line)
    k = re.match(r"^(\S+)(\s+)(\S+)(.*)$", line)
    if m and not m.group(2).endswith("FAST_SPEED") and not m.group(2).startswith("BEH_"):
        kind, name = m.group(1), m.group(2)
        table = {"BUTTON": btn, "LED": led, "ENC": enc}[kind]
        sr, pin = table.get(name, (0, 0))
        seen.add((kind, name))
        line = "%s_%-36s %3d %3d%s" % (kind, name, sr, pin, "   DETENTED3" if kind == "ENC" else "")
    elif k and k.group(1) in gp:
        line = "%-16s %d" % (k.group(1), gp[k.group(1)])
    elif k and k.group(1) == "SRIO_NUM_SR":
        line = "SRIO_NUM_SR    15"
    elif k and k.group(1) in ("BLM8X8_ENABLED", "BLM_ENABLED", "BLM_BUTTONS_ENABLED"):
        line = "%s 0" % k.group(1)
    elif k and k.group(1) == "TPD_ENABLED":
        line = "TPD_ENABLED 0"
    out.append(line)
missing = [("BUTTON", n) for n in btn if ("BUTTON", n) not in seen] + [("LED", n) for n in led if ("LED", n) not in seen] + \
          [("ENC", n) for n in enc if ("ENC", n) not in seen]
assert not missing, missing
head = """##################################################
# Hardware configuration: 4-OLED front panel (branch four-screens-usb)
# generated by myproject/hardware/make_hwcfg.py - do not edit by hand
# left PCB = DIN SR 1-3, DOUT SR 1-2; column PCB 1..4 = DIN SR 4-6, 7-9, 10-12, 13-15
# big-key LEDs: virtual DOUT SR 3-9, shown on the SK6812 chain (seq_rgbled.c)
# encoders: if one turns the wrong way, use the odd pin (1, 3, 5, 7) of its pair
##################################################
OLED_SSD1322     4
OLED_CONTRAST    159
RGBLED_ENABLED   1
RGBLED_BRIGHTNESS 64
"""
open(OUT, "w", newline="").write((head + "\n".join(out)).replace("\n", "\r\n"))
used = {}
for n, v in btn.items():
    assert v not in used, ("DIN pin used twice", n, used.get(v)); used[v] = n
for n, (s, p) in enc.items():
    for q in (p, p + 1):
        assert (s, q) not in used, ("DIN pin used twice", n, used.get((s, q))); used[(s, q)] = n
print("saved", OUT, "buttons", len(btn), "encoders", len(enc), "LEDs", len(led), "DIN pins used", len(used))
